USE sqlstudy;

-- 정규화 전에는 한 행에 주문상품이 '0001 1개, 0002 10개'처럼 뭉쳐 있었음
-- 1정규화: 셀 하나에 값 하나만 두고, 반복되는 부분을 행 방향으로 늘린 다음
--          반복을 찾아 테이블을 나누고 기본키를 정함 (주문 / 주문상품)
-- 2정규화: 기본키로 정해지는 열과 아닌 열을 나눔 (상품명은 상품코드만으로 정해짐)
-- 3정규화: 기본키 말고 다른 곳의 중복도 나눔 (성명, 연락처를 고객 테이블로)

SELECT * FROM 주문;
SELECT * FROM 주문상품;
SELECT * FROM 고객;

-- 나눠진 테이블은 결합해서 원래 형태로 볼 수 있음
SELECT 주문.주문번호, 주문.날짜, 고객.성명, 상품.상품명, 주문상품.개수
FROM 주문
INNER JOIN 고객 ON 주문.고객번호 = 고객.고객번호
INNER JOIN 주문상품 ON 주문.주문번호 = 주문상품.주문번호
INNER JOIN 상품 ON 주문상품.상품코드 = 상품.상품코드
ORDER BY 주문.주문번호, 주문상품.상품코드;

-- 정규화를 하는 이유는 하나의 데이터가 한 곳에만 있게 하려는 것
-- 한 곳에만 있으면 값이 바뀌어도 한 군데만 고치면 됨
-- 고객 연락처가 바뀌어도 고객 테이블만 고치면 주문 전체에 반영됨
UPDATE 고객 SET 연락처 = '010-1111' WHERE 고객번호 = 1;
SELECT * FROM 고객;
