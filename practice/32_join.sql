-- 32강 테이블 결합
USE sqlstudy;

SELECT * FROM 상품;
SELECT * FROM 재고수;

-- FROM에 테이블을 여러 개 쓰면 교차결합이 돼서 모든 조합(곱집합)이 나옴
SELECT * FROM 상품, 재고수;  -- 3 x 3 = 9행
SELECT * FROM 상품 CROSS JOIN 재고수;  -- 같은 결과

-- 곱집합에서 조건에 맞는 조합만 고르는 게 내부결합
-- 열 이름이 같으면 테이블명을 붙여서 구분함
SELECT * FROM 상품, 재고수
WHERE 상품.상품코드 = 재고수.상품코드;  -- 구식 방법

SELECT 상품.상품명, 재고수.재고수 FROM 상품, 재고수
WHERE 상품.상품코드 = 재고수.상품코드
AND 상품.상품분류 = '식료품';  -- 상품○○ 200, 상품×× 500

-- 요즘은 INNER JOIN을 씀. ON에는 결합조건, WHERE에는 검색조건
SELECT 상품.상품명, 재고수.재고수
FROM 상품 INNER JOIN 재고수
ON 상품.상품코드 = 재고수.상품코드
WHERE 상품.상품분류 = '식료품';

-- 테이블에 별명을 붙이면 짧게 쓸 수 있음
SELECT S.상품명, M.메이커명
FROM 상품2 S INNER JOIN 메이커 M
ON S.메이커코드 = M.메이커코드;
-- 상품2의 메이커코드처럼 다른 테이블의 기본키를 참조하는 열을 외부키라고 함

-- 재고수에 없는 0009는 내부결합 결과에서 빠짐
SELECT 상품3.상품명, 재고수.재고수
FROM 상품3 INNER JOIN 재고수
ON 상품3.상품코드 = 재고수.상품코드
WHERE 상품3.상품분류 = '식료품';  -- 상품○○, 상품××

-- 한쪽에만 있는 행도 넣고 싶으면 외부결합
SELECT 상품3.상품명, 재고수.재고수
FROM 상품3 LEFT JOIN 재고수
ON 상품3.상품코드 = 재고수.상품코드
WHERE 상품3.상품분류 = '식료품';  -- 추가상품은 재고수가 NULL로 나옴

-- LEFT JOIN은 왼쪽 테이블 기준, RIGHT JOIN은 오른쪽 테이블 기준
SELECT 상품3.상품명, 재고수.재고수
FROM 재고수 RIGHT JOIN 상품3
ON 상품3.상품코드 = 재고수.상품코드
WHERE 상품3.상품분류 = '식료품';  -- 위와 같은 결과
